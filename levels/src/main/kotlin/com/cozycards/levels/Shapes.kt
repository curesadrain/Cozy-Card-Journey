package com.cozycards.levels

/**
 * Hand-authored board silhouettes. `.` = playable cell, `#` = void.
 * Every shape is left/right symmetric and connected; [irregular] shapes are used by
 * chapters that feature unusual boards.
 */
data class BoardShape(val name: String, val rows: List<String>, val irregular: Boolean) {
    val width get() = rows[0].length
    val height get() = rows.size
    fun isCell(x: Int, y: Int) = rows[y][x] == '.'
    val cellCount get() = rows.sumOf { r -> r.count { it == '.' } }
}

